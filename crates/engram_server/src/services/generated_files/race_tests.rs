//! Deterministic editor interleavings at the actual publication boundaries.
//! All files, retained fault evidence, hooks and database handles belong to the
//! fixture, including unwind teardown. No artifacts escape its one directory.
use super::*;
use std::path::PathBuf;

fn fixture() -> (tempfile::TempDir, Registry, PathBuf) {
    let owned = tempfile::tempdir().unwrap();
    let registry = Registry::open(&owned.path().join("registry.redb")).unwrap();
    let root = owned.path().join("repo");
    std::fs::create_dir(&root).unwrap();
    (owned, registry, root)
}

fn artifacts(text: &str) -> Vec<(String, String)> { vec![("policy.md".into(), text.into())] }
fn receipt(registry: &Registry) -> Receipt {
    serde_json::from_str(&registry.get_meta("project", "generated_artifacts:race").unwrap().unwrap()).unwrap()
}
fn candidate(root: &Path, text: &str) -> PathBuf {
    let path = root.join(format!("human-{}.md", uuid::Uuid::new_v4().simple()));
    std::fs::write(&path, text).unwrap();
    path
}

