#[test]
fn guarded_publication_preserves_human_winner_and_journaled_preimage_after_retirement() {
    let (owned, registry, root) = fixture();
    publish(&registry, "project", &root, "race", &artifacts("original generated bytes")).unwrap();
    {
        let _hook = HookOwner::install(Box::new(|event, relative, root| {
            if event == Event::Retired && relative == "policy.md" {
                use std::io::Write;
                let mut winner = std::fs::OpenOptions::new().write(true).create_new(true).open(root.join(relative))?;
                winner.write_all(b"HUMAN won the newly absent name")?;
                winner.sync_all()?;
            }
            Ok(())
        }));
        let failure = publish(&registry, "project", &root, "race", &artifacts("complete generated proposal"))
            .unwrap_err().downcast::<PublicationFailure>().unwrap();
        assert!(failure.report.written.is_empty());
        assert_eq!(failure.report.outcomes["policy.md"], "preserved_changed");
        assert!(failure.report.notes.iter().any(|note| note.contains("RETAINED publication recovery")));
    }
    assert_eq!(std::fs::read_to_string(root.join("policy.md")).unwrap(), "HUMAN won the newly absent name");
    let state = receipt(&registry);
    let pending = state.pending.unwrap();
    assert_eq!(pending.phase, "retired");
    assert_eq!(state.files["policy.md"], blake3::hash(b"original generated bytes").to_hex().to_string());
    assert_eq!(std::fs::read_to_string(root.join(pending.recovery.unwrap())).unwrap(), "original generated bytes");
    assert_eq!(std::fs::read_to_string(root.join(pending.staged.unwrap())).unwrap(), "complete generated proposal");
    let before_retry = registry.get_meta("project", "generated_artifacts:race").unwrap();
    let retry = publish(&registry, "project", &root, "race", &artifacts("another proposal")).unwrap();
    assert_eq!(retry.outcomes["policy.md"], "preserved_unverifiable");
    assert!(retry.written.is_empty());
    assert_eq!(registry.get_meta("project", "generated_artifacts:race").unwrap(), before_retry);
    assert_eq!(std::fs::read_to_string(root.join("policy.md")).unwrap(), "HUMAN won the newly absent name");
    drop(registry);
    owned.close().unwrap();
}

