#[test]
fn whole_root_authority_precedes_receipt_hash_and_stale_removal_observations() {
    for boundary in [Event::Observed, Event::BeforeRemoval] {
        let (owned, registry, root) = fixture();
        publish(&registry, "project", &root, "race", &artifacts("same receipted bytes")).unwrap();
        let replacement = owned.path().join("replacement-root");
        std::fs::create_dir(&replacement).unwrap();
        std::fs::write(replacement.join("policy.md"), "same receipted bytes").unwrap();
        std::fs::write(replacement.join("human.md"), "Unrelated root authority").unwrap();
        let moved = owned.path().join("repo-old");
        let replacement_hook = replacement.clone();
        let moved_hook = moved.clone();
        let before = registry.get_meta("project", "generated_artifacts:race").unwrap();
        {
            let _hook = HookOwner::install(Box::new(move |event, relative, root| {
                if event == boundary && relative == "policy.md" {
                    // This is the former check->lock window. Matching file bytes
                    // in another root must not let a later guard rebind scope.
                    assert!(std::fs::rename(root, &moved_hook).is_err(),
                        "The original root must already deny relocation before observation");
                    assert!(std::fs::rename(&replacement_hook, root).is_err());
                    anyhow::bail!("root replacement refused at synchronized boundary");
                }
                Ok(())
            }));
            let desired = if boundary == Event::BeforeRemoval { vec![] } else { artifacts("new generated proposal") };
            let failure = publish(&registry, "project", &root, "race", &desired)
                .unwrap_err().downcast::<PublicationFailure>().unwrap();
            assert!(failure.report.written.is_empty());
            assert!(failure.to_string().contains("root replacement refused"));
        }
        assert!(!moved.exists());
        assert_eq!(std::fs::read_to_string(root.join("policy.md")).unwrap(), "same receipted bytes");
        assert_eq!(std::fs::read_to_string(replacement.join("policy.md")).unwrap(), "same receipted bytes");
        assert_eq!(std::fs::read_to_string(replacement.join("human.md")).unwrap(), "Unrelated root authority");
        assert_eq!(registry.get_meta("project", "generated_artifacts:race").unwrap(), before);
        drop(registry);
        owned.close().unwrap();
    }
}

