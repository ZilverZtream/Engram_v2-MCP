fn no_recovery_files(root: &Path) {
    let mut pending = vec![root.to_owned()];
    let mut entries = 0usize;
    while let Some(directory) = pending.pop() {
        for entry in std::fs::read_dir(directory).unwrap() {
            entries += 1; assert!(entries < 512);
            let entry = entry.unwrap();
            if entry.file_type().unwrap().is_dir() { pending.push(entry.path()); }
            else {
                let name = entry.file_name().to_string_lossy().into_owned();
                assert!(!name.starts_with(".engram-"), "Owned recovery file was stranded: {name}");
            }
        }
    }
}

#[test]
fn same_bundle_retry_converges_after_each_owned_publication_interruption() {
    for boundary in [Event::Prepared, Event::Retired, Event::Installed] {
        let (owned, registry, root) = fixture();
        publish(&registry, "project", &root, "race", &artifacts("original complete policy")).unwrap();
        {
            let _hook = HookOwner::install(Box::new(move |event, relative, _| {
                if event == boundary && relative == "policy.md" { anyhow::bail!("owned injected interruption"); }
                Ok(())
            }));
            publish(&registry, "project", &root, "race", &artifacts("new complete policy")).unwrap_err();
        }
        assert!(receipt(&registry).pending.is_some());
        let retry = publish(&registry, "project", &root, "race", &artifacts("new complete policy")).unwrap();
        assert!(matches!(retry.outcomes["policy.md"], "written" | "unchanged_receipt_owned"));
        assert!(retry.notes.iter().any(|note| note.contains("Reconciled")));
        assert_eq!(std::fs::read(root.join("policy.md")).unwrap(), b"new complete policy");
        assert_eq!(receipt(&registry).files["policy.md"], blake3::hash(b"new complete policy").to_hex().to_string());
        assert!(receipt(&registry).pending.is_none());
        no_recovery_files(&root);
        let again = publish(&registry, "project", &root, "race", &artifacts("new complete policy")).unwrap();
        assert!(again.written.is_empty());
        drop(registry); owned.close().unwrap();
    }
}

