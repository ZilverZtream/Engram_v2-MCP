#[test]
fn guarded_dependency_remains_protected_until_root_and_receipt_publication() {
    let (owned, registry, root) = fixture();
    let dependencies = BTreeMap::from([("AGENTS.md".into(), vec!["policy.md".into()])]);
    let first = vec![("policy.md".into(), "complete policy one".into()), ("AGENTS.md".into(), "root one".into())];
    publish_bundle(&registry, "project", &root, "race", &first, &dependencies, &BTreeMap::new()).unwrap();
    {
        let _hook = HookOwner::install(Box::new(|event, relative, root| {
            if event == Event::BeforeDependent && relative == "AGENTS.md" {
                let human = candidate(root, "HUMAN companion proposal");
                assert!(std::fs::write(root.join("policy.md"), b"HUMAN in-place proposal").is_err(),
                    "The held companion must deny a concurrent in-place writer");
                assert!(std::fs::rename(&human, root.join("policy.md")).is_err(),
                    "The held companion must deny a concurrent atomic replacement");
                assert_eq!(std::fs::read_to_string(human)?, "HUMAN companion proposal");
            }
            Ok(())
        }));
        let next = vec![("policy.md".into(), "complete policy two".into()), ("AGENTS.md".into(), "root two".into())];
        let report = publish_bundle(&registry, "project", &root, "race", &next, &dependencies, &BTreeMap::new()).unwrap();
        assert_eq!(report.outcomes["AGENTS.md"], "written");
    }
    assert_eq!(std::fs::read_to_string(root.join("policy.md")).unwrap(), "complete policy two");
    assert_eq!(std::fs::read_to_string(root.join("AGENTS.md")).unwrap(), "root two");
    assert!(receipt(&registry).pending.is_none());
    drop(registry);
    owned.close().unwrap();
}

